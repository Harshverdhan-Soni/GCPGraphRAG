// src/components/ReportModal.jsx
import { useState } from "react";
import { api } from "../api/client";

export default function ReportModal({ result, query, config, onClose }) {
  const [md,        setMd]        = useState("");
  const [loading,   setLoading]   = useState(false);
  const [pdfLoading,setPdfLoading]= useState(false);
  const [error,     setError]     = useState(null);
  const [generated, setGenerated] = useState(false);

  // ── Generate markdown from server ────────────────────────────────
  async function generate() {
    setLoading(true); setError(null);
    try {
      const res = await api.generateReport({
        query,
        response:    result.response    || "",
        metrics:     result.metrics     || {},
        token_stats: result.token_stats || {},
        graph_stats: result.graph_stats || {},
        config:      config             || {},
        latency_ms:  result.latency_ms  || 0,
        corpus_size: result.corpus_size || 0,
      });
      setMd(res.markdown);
      setGenerated(true);
    } catch (e) { setError(e.message); }
    finally     { setLoading(false); }
  }

  // ── Download .md ──────────────────────────────────────────────────
  function downloadMd() {
    const blob = new Blob([md], { type: "text/markdown" });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement("a");
    a.href     = url;
    a.download = `gcp_graphrag_report_${Date.now()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  }

  // ── Download PDF via browser print ───────────────────────────────
  async function downloadPdf() {
    setPdfLoading(true);
    try {
      // Convert markdown to styled HTML for printing
      const html = mdToHtml(md);
      const printWin = window.open("", "_blank", "width=900,height=700");
      printWin.document.write(`<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8"/>
  <title>GCP-GraphRAG Report</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      font-family: 'Segoe UI', Arial, sans-serif;
      font-size: 12px; line-height: 1.6;
      color: #111; background: #fff;
      padding: 32px 48px;
      max-width: 820px; margin: 0 auto;
    }
    h1 { font-size: 22px; color: #0c447c; border-bottom: 2px solid #0c447c;
         padding-bottom: 8px; margin-bottom: 20px; }
    h2 { font-size: 16px; color: #1e3a5f; margin: 24px 0 10px;
         border-bottom: 1px solid #dde1ea; padding-bottom: 4px; }
    h3 { font-size: 13px; color: #374151; margin: 16px 0 8px; }
    p  { margin-bottom: 10px; }
    table { width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 11px; }
    th { background: #e6f1fb; color: #0c447c; text-align: left;
         padding: 6px 10px; border: 1px solid #c0d4ea; }
    td { padding: 5px 10px; border: 1px solid #dde1ea; }
    tr:nth-child(even) td { background: #f8fafd; }
    code, pre { font-family: 'Consolas', monospace; font-size: 10px;
                background: #f3f4f6; padding: 2px 5px; border-radius: 3px; }
    pre { padding: 12px; margin: 10px 0; white-space: pre-wrap;
          border: 1px solid #e5e7eb; border-radius: 4px; }
    blockquote { border-left: 3px solid #0c447c; margin: 12px 0;
                 padding: 6px 12px; color: #374151; background: #f0f6ff; }
    strong { color: #0c447c; }
    hr { border: none; border-top: 1px solid #dde1ea; margin: 20px 0; }
    .footer { margin-top: 32px; font-size: 10px; color: #6b7280;
              border-top: 1px solid #dde1ea; padding-top: 10px; }
    @media print {
      body { padding: 16px 24px; }
      h1 { font-size: 18px; }
      h2 { font-size: 14px; }
    }
  </style>
</head>
<body>
${html}
<div class="footer">Generated by GCP-GraphRAG Research Platform</div>
</body>
</html>`);
      printWin.document.close();
      // Wait for content to render, then print
      setTimeout(() => {
        printWin.focus();
        printWin.print();
        printWin.close();
      }, 600);
    } catch (e) {
      setError(`PDF export failed: ${e.message}`);
    } finally {
      setPdfLoading(false);
    }
  }

  function copyToClipboard() {
    navigator.clipboard.writeText(md).catch(() => {});
  }

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal report-modal" onClick={e => e.stopPropagation()}>
        <div className="modal-header">
          <span className="modal-title">Research Report</span>
          <span className="modal-badge">GCP-GraphRAG v2.0</span>
          <button className="modal-close" onClick={onClose}>✕</button>
        </div>

        {error && <div className="modal-error">⚠ {error}</div>}

        {!generated ? (
          <div className="report-intro">
            <div className="report-intro-icon">📄</div>
            <div className="report-intro-title">Generate Evaluation Report</div>
            <div className="report-intro-desc">Creates a structured report including:</div>
            <div className="report-checklist">
              {[
                "Pipeline configuration",
                "Evaluation metrics (F1, ROUGE-L, Recall@5…)",
                "Comparison with RAG, GraphRAG, mRAG baselines",
                "Token budget and context reduction stats",
                "Graph density and structure metrics",
                "Generated response",
                "Key findings summary",
              ].map((item, i) => (
                <div key={i} className="report-check-item">
                  <span className="report-check-icon">✓</span>
                  <span>{item}</span>
                </div>
              ))}
            </div>
            <button className="report-generate-btn" onClick={generate} disabled={loading}>
              {loading
                ? <><span className="spinner-sm"/> Generating…</>
                : "Generate Report"}
            </button>
          </div>
        ) : (
          <>
            <div className="report-actions">
              <button className="report-action-btn" onClick={downloadMd}>
                ⬇ Download .md
              </button>
              <button className="report-action-btn report-pdf-btn"
                onClick={downloadPdf} disabled={pdfLoading}>
                {pdfLoading
                  ? <><span className="spinner-sm"/> Preparing PDF…</>
                  : "🖨 Download PDF"}
              </button>
              <button className="report-action-btn" onClick={copyToClipboard}>
                ⎘ Copy markdown
              </button>
              <button className="report-action-btn report-regen-btn"
                onClick={() => setGenerated(false)}>
                ↺ Regenerate
              </button>
            </div>
            <div className="report-body">
              <pre className="report-content">{md}</pre>
            </div>
          </>
        )}
      </div>
    </div>
  );
}

// ── Minimal markdown → HTML converter ────────────────────────────────
function mdToHtml(md) {
  return md
    .split("\n")
    .map(line => {
      if (line.startsWith("# "))     return `<h1>${esc(line.slice(2))}</h1>`;
      if (line.startsWith("## "))    return `<h2>${esc(line.slice(3))}</h2>`;
      if (line.startsWith("### "))   return `<h3>${esc(line.slice(4))}</h3>`;
      if (line.startsWith("---"))    return `<hr/>`;
      if (line.startsWith("> "))     return `<blockquote>${esc(line.slice(2))}</blockquote>`;
      if (line.startsWith("```"))    return line === "```" ? "</pre>" : `<pre>`;
      if (line.startsWith("|")) {
        const cells = line.split("|").filter((_, i, a) => i > 0 && i < a.length - 1);
        if (line.includes("---")) {
          return ""; // separator row
        }
        const tag = line.includes("**") || cells.some(c => c.trim().startsWith("**")) ? "th" : "td";
        return `<tr>${cells.map(c =>
          `<${tag}>${esc(c.trim()).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")}</${tag}>`
        ).join("")}</tr>`;
      }
      if (line.trim() === "") return "<p></p>";
      // Inline formatting
      let out = esc(line)
        .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
        .replace(/`(.+?)`/g, "<code>$1</code>");
      return `<p>${out}</p>`;
    })
    .join("\n")
    // Wrap table rows
    .replace(/(<tr>.*?<\/tr>\n?)+/gs, m => `<table>${m}</table>`);
}

function esc(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
